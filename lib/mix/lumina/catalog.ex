defmodule Mix.Lumina.Catalog do
  @moduledoc """
  Renders the test catalog (`doc/tests/CATALOG.md`) from fixture metadata
  and unit test sources. See `mix lumina.test_catalog`.
  """

  alias Mix.Lumina.{Fixtures, RFC, TestScanner}

  @default_path "doc/tests/CATALOG.md"

  @doc "Default location of the catalog."
  @spec path() :: Path.t()
  def path, do: @default_path

  @doc """
  Renders the catalog for `fixtures`, the unit test `modules` (from
  `Mix.Lumina.TestScanner`) and the test TALs (`Mix.Lumina.TALCases`).
  Links are relative to `catalog_path`.
  """
  @spec render([Fixtures.fixture()], [TestScanner.test_module()], Path.t(), [map()]) :: String.t()
  def render(fixtures, modules, catalog_path \\ @default_path, tal_cases \\ []) do
    base = Path.dirname(catalog_path)
    modules = modules |> Enum.filter(& &1.exunit?) |> Enum.sort_by(&{&1.file, &1.line})

    """
    # Test catalog

    <!-- Generated by `mix lumina.test_catalog` from fixture metadata and test sources. Do not edit by hand. -->

    Every test, what it checks and why it exists. See [testing.md](#{relative("doc/testing.md", base)}) for the conventions.

    - #{fixture_summary(fixtures)}
    - #{tal_summary(tal_cases)}
    - #{unit_summary(modules)}

    ## Barry fixtures

    Repositories generated with Barry, and what a correct validator must conclude from each.

    #{fixtures_body(fixtures, base)}

    ## Test TALs

    Hand-written Trust Anchor Locators, valid and malformed, and what a correct TAL parser must report for each (RFC 8630 §2.2, D-002).

    #{tals_body(tal_cases, base)}

    ## Unit tests

    Grouped by test module. Doctests are not listed: they are documented by the function docs they come from.

    #{units_body(modules, base)}
    """
  end

  defp fixtures_body([], _base), do: "No fixtures yet."

  defp fixtures_body(fixtures, base) do
    fixtures
    |> Enum.group_by(& &1.milestone)
    |> Enum.sort()
    |> Enum.map_join("\n\n", fn {milestone, group} ->
      entries = group |> Enum.sort_by(& &1.id) |> Enum.map_join("\n\n", &entry(&1, base))
      "### #{milestone}\n\n#{entries}"
    end)
  end

  defp tals_body([], _base), do: "No test TALs yet."

  defp tals_body(cases, base) do
    cases
    |> Enum.sort_by(& &1.id)
    |> Enum.map_join("\n\n", fn tal_case ->
      dir = relative(tal_case.dir, base)

      """
      #### `#{tal_case.id}`: #{tal_case.title}

      #{String.trim(tal_case.rationale)}

      - **Expected:** #{tal_expected(tal_case.expected)}
      - **RFC:** #{Enum.map_join(tal_case.rfc, ", ", &rfc_link(&1, base))}
      - **Files:** [TAL](#{dir}/case.tal) · [metadata](#{dir}/case.exs)\
      """
    end)
  end

  defp tal_expected(:valid), do: "valid"

  defp tal_expected({:valid, warnings: warnings}),
    do:
      "valid, with warnings: " <> Enum.map_join(warnings, ", ", &"`#{&1.rule}` (line #{&1.line})")

  defp tal_expected({:invalid, %{line: line, rule: rule}}),
    do: "invalid: `#{rule}` at line #{line}"

  defp tal_summary(cases) do
    counts = Enum.frequencies_by(cases, &tal_kind(&1.expected))

    "#{length(cases)} test #{plural(length(cases), "TAL")}: #{Map.get(counts, :valid, 0)} valid, " <>
      "#{Map.get(counts, :warning, 0)} with warnings, #{Map.get(counts, :invalid, 0)} invalid."
  end

  defp tal_kind(:valid), do: :valid
  defp tal_kind({:valid, _}), do: :warning
  defp tal_kind({:invalid, _}), do: :invalid

  defp units_body([], _base), do: "No unit tests yet."

  defp units_body(modules, base), do: Enum.map_join(modules, "\n\n", &unit_module(&1, base))

  defp unit_module(module, base) do
    file = relative(module.file, base)

    tests =
      case module.tests do
        [] -> "No tests of its own (doctests only)."
        tests -> Enum.map_join(tests, "\n", &unit_test(&1, base))
      end

    """
    ### `#{module.name}`

    [#{module.file}](#{file})

    #{module.moduledoc |> to_string() |> String.trim()}

    #{tests}\
    """
  end

  defp unit_test(test, base) do
    prefix = if test.describe, do: "*#{test.describe}:* ", else: ""

    refs =
      if test.refs == [],
        do: "",
        else: " (RFC #{Enum.map_join(test.refs, ", ", &rfc_link(&1, base))})"

    line = "- #{prefix}#{test.name}#{refs}"

    case test.doc do
      nil ->
        line

      doc ->
        line <>
          "\n" <>
          (doc
           |> String.trim()
           |> String.split("\n")
           |> Enum.map_join("\n", &"  #{String.trim(&1)}"))
    end
  end

  defp fixture_summary(fixtures) do
    valid = Enum.count(fixtures, &(&1.expected == :valid))

    "#{length(fixtures)} Barry #{plural(length(fixtures), "fixture")}: #{valid} valid, #{length(fixtures) - valid} invalid."
  end

  defp unit_summary(modules) do
    count = modules |> Enum.map(&length(&1.tests)) |> Enum.sum()

    "#{count} unit #{plural(count, "test")} in #{length(modules)} #{plural(length(modules), "module")}."
  end

  defp entry(fixture, base) do
    case_dir = relative(fixture.dir, base)

    """
    #### `#{fixture.id}`: #{fixture.title}

    #{fixture.rationale |> String.trim()}

    - **Expected:** #{expected(fixture.expected)}
    - **RFC:** #{Enum.map_join(fixture.rfc, ", ", &rfc_link(&1, base))}
    - **Files:** [descriptor](#{case_dir}/case.repo) · [metadata](#{case_dir}/case.exs) · [rsync tree](#{case_dir}/rsync)\
    """
  end

  defp expected(:valid), do: "valid"

  defp expected({:invalid, rejects}) do
    lines = Enum.map_join(rejects, "\n", &"  - `#{&1.object}`: #{&1.reason}")
    "invalid. A validator must reject:\n#{lines}"
  end

  # Links to the local copy; numbered sections also get a deep link into the
  # rfc-editor.org HTML.
  defp rfc_link(string, base) do
    {:ok, %{rfc: rfc, section: section}} = RFC.parse(string)
    local = "[#{rfc} §#{section}](#{relative("doc/rfc/rfc#{rfc}.txt", base)})"

    if section =~ ~r/\A[0-9]/,
      do: "#{local} ([html](https://www.rfc-editor.org/rfc/rfc#{rfc}.html#section-#{section}))",
      else: local
  end

  defp relative(path, base) do
    from = base |> Path.expand() |> Path.split()
    to = path |> Path.expand() |> Path.split()
    common = Enum.zip(from, to) |> Enum.take_while(fn {a, b} -> a == b end) |> length()
    ups = List.duplicate("..", length(from) - common)
    Path.join(ups ++ Enum.drop(to, common))
  end

  defp plural(1, word), do: word
  defp plural(_, word), do: word <> "s"
end
