defmodule Mix.Lumina.CatalogTest do
  @moduledoc """
  Tests rendering of doc/tests/CATALOG.md: content, grouping, order, links
  and determinism. The catalog is committed and checked in CI, so output
  must not depend on input order.
  """
  use ExUnit.Case, async: true

  alias Mix.Lumina.Catalog

  @valid %{
    id: "m4-chain-ok",
    title: "Valid chain",
    milestone: "M4",
    rationale: "Baseline: a correct chain must be accepted.\n",
    rfc: ["6487#4"],
    expected: :valid,
    dir: "test/fixtures/barry/m4-chain-ok"
  }

  @invalid %{
    id: "m4-ca-expired",
    title: "Expired CA certificate",
    milestone: "M4",
    rationale: "Catches validators that skip notAfter on CA certificates.\n",
    rfc: ["6487#4.6.2", "5280#A.1"],
    expected: {:invalid, [%{object: "ta/ca1.cer", reason: "notAfter is in the past"}]},
    dir: "test/fixtures/barry/m4-ca-expired"
  }

  @earlier %{
    @valid
    | id: "m0-minimal-valid",
      title: "Minimal",
      milestone: "M0",
      dir: "test/fixtures/barry/m0-minimal-valid"
  }

  test "says so when there are no fixtures or unit tests" do
    catalog = Catalog.render([], [])

    assert catalog =~
             "- 0 Barry fixtures: 0 valid, 0 invalid.\n- 0 test TALs: 0 valid, 0 with warnings, 0 invalid.\n- 0 unit tests in 0 modules."

    assert catalog =~ "No fixtures yet."
    assert catalog =~ "No unit tests yet."
  end

  test "marks the file as generated" do
    assert Catalog.render([], []) =~ "Generated by `mix lumina.test_catalog`"
  end

  test "groups by milestone and sorts by id within a milestone" do
    catalog = Catalog.render([@valid, @invalid, @earlier], [])

    assert catalog =~ "3 Barry fixtures: 2 valid, 1 invalid."

    headings = Regex.scan(~r/^##+ .*$/m, catalog) |> List.flatten()

    assert headings == [
             "## Barry fixtures",
             "### M0",
             "#### `m0-minimal-valid`: Minimal",
             "### M4",
             "#### `m4-ca-expired`: Expired CA certificate",
             "#### `m4-chain-ok`: Valid chain",
             "## Test TALs",
             "## Unit tests"
           ]
  end

  test "an entry shows the rationale, expected outcome, RFC links and files" do
    catalog = Catalog.render([@invalid], [])

    assert catalog =~
             "Catches validators that skip notAfter on CA certificates.\n\n- **Expected:**"

    assert catalog =~
             "- **Expected:** invalid. A validator must reject:\n  - `ta/ca1.cer`: notAfter is in the past\n"

    assert catalog =~
             "[6487 §4.6.2](../rfc/rfc6487.txt) ([html](https://www.rfc-editor.org/rfc/rfc6487.html#section-4.6.2))"

    # Appendices only link to the local copy.
    assert catalog =~ "[5280 §A.1](../rfc/rfc5280.txt)\n"

    assert catalog =~
             "[descriptor](../../test/fixtures/barry/m4-ca-expired/case.repo) · " <>
               "[metadata](../../test/fixtures/barry/m4-ca-expired/case.exs) · " <>
               "[rsync tree](../../test/fixtures/barry/m4-ca-expired/rsync)"
  end

  test "a valid fixture says so" do
    assert Catalog.render([@valid], []) =~ "- **Expected:** valid\n"
  end

  test "links are relative to where the catalog is written" do
    catalog = Catalog.render([@valid], [], "CATALOG.md")
    assert catalog =~ "[6487 §4](doc/rfc/rfc6487.txt)"
    assert catalog =~ "(test/fixtures/barry/m4-chain-ok/case.repo)"
  end

  @module_a %{
    file: "test/a_test.exs",
    line: 1,
    name: "ATest",
    moduledoc: "Covers A.\n",
    exunit?: true,
    tests: [
      %{name: "plain test", describe: nil, refs: [], doc: nil},
      %{
        name: "rejects a bad version",
        describe: "parse/1",
        refs: ["9582#4.1"],
        doc: "Regression for a version check\nthat was skipped.\n"
      }
    ]
  }

  @module_b %{
    file: "test/b_test.exs",
    line: 1,
    name: "BTest",
    moduledoc: "Covers B.",
    exunit?: true,
    tests: []
  }

  @helper %{
    file: "test/a_test.exs",
    line: 20,
    name: "AHelper",
    moduledoc: nil,
    exunit?: false,
    tests: []
  }

  describe "test TALs" do
    @tal_case %{
      id: "invalid-two-blank-lines",
      title: "Two blank lines",
      rationale: "Why it exists.",
      rfc: ["8630#2.2"],
      expected: {:invalid, %{line: 3, rule: :extra_blank_line}},
      dir: "test/fixtures/tals/cases/invalid-two-blank-lines"
    }

    test "lists each test TAL with its expected outcome, RFC links and files" do
      catalog = Catalog.render([], [], "doc/tests/CATALOG.md", [@tal_case])

      assert catalog =~ "- 1 test TAL: 0 valid, 0 with warnings, 1 invalid."
      assert catalog =~ "#### `invalid-two-blank-lines`: Two blank lines\n\nWhy it exists.\n"
      assert catalog =~ "- **Expected:** invalid: `extra_blank_line` at line 3\n"
      assert catalog =~ "[TAL](../../test/fixtures/tals/cases/invalid-two-blank-lines/case.tal)"
    end

    test "valid cases with warnings show each warning and its line" do
      warned = %{
        @tal_case
        | expected: {:valid, warnings: [%{line: 2, rule: :trailing_whitespace}]}
      }

      assert Catalog.render([], [], "doc/tests/CATALOG.md", [warned]) =~
               "valid, with warnings: `trailing_whitespace` (line 2)"
    end

    test "says so when there are no test TALs" do
      assert Catalog.render([], []) =~ "No test TALs yet."
    end
  end

  describe "unit tests" do
    test "lists each test module with its moduledoc, file and tests, in file order" do
      catalog = Catalog.render([], [@module_b, @module_a])

      assert catalog =~ "- 2 unit tests in 2 modules."

      assert catalog =~
               "### `ATest`\n\n[test/a_test.exs](../../test/a_test.exs)\n\nCovers A.\n\n- plain test\n"

      assert :binary.match(catalog, "### `ATest`") < :binary.match(catalog, "### `BTest`")
    end

    test "shows the describe block, RFC references and doc tag of a test" do
      catalog = Catalog.render([], [@module_a])

      assert catalog =~
               "- *parse/1:* rejects a bad version (RFC [9582 §4.1](../rfc/rfc9582.txt) " <>
                 "([html](https://www.rfc-editor.org/rfc/rfc9582.html#section-4.1)))\n" <>
                 "  Regression for a version check\n  that was skipped.\n"
    end

    test "says so for a module with only doctests" do
      assert Catalog.render([], [@module_b]) =~
               "Covers B.\n\nNo tests of its own (doctests only)."
    end

    test "leaves out helper modules that don't use ExUnit.Case" do
      refute Catalog.render([], [@module_a, @helper]) =~ "AHelper"
    end
  end

  test "rendering is deterministic regardless of input order" do
    assert Catalog.render([@valid, @invalid, @earlier], [@module_b, @module_a]) ==
             Catalog.render([@earlier, @invalid, @valid], [@module_a, @module_b])
  end
end
