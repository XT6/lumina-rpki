defmodule Mix.Lumina.CatalogTest do
  use ExUnit.Case, async: true

  alias Mix.Lumina.Catalog

  @valid %{
    id: "m4-chain-ok",
    title: "Valid chain",
    milestone: "M4",
    rationale: "Baseline: a correct chain must be accepted.\n",
    rfc: ["6487#4"],
    expected: :valid,
    dir: "test/fixtures/barry/m4-chain-ok"
  }

  @invalid %{
    id: "m4-ca-expired",
    title: "Expired CA certificate",
    milestone: "M4",
    rationale: "Catches validators that skip notAfter on CA certificates.\n",
    rfc: ["6487#4.6.2", "5280#A.1"],
    expected: {:invalid, [%{object: "ta/ca1.cer", reason: "notAfter is in the past"}]},
    dir: "test/fixtures/barry/m4-ca-expired"
  }

  @earlier %{
    @valid
    | id: "m0-minimal-valid",
      title: "Minimal",
      milestone: "M0",
      dir: "test/fixtures/barry/m0-minimal-valid"
  }

  test "says so when there are no fixtures" do
    catalog = Catalog.render([])
    assert catalog =~ "0 fixtures: 0 valid, 0 invalid."
    assert catalog =~ "No fixtures yet."
  end

  test "marks the file as generated" do
    assert Catalog.render([]) =~ "Generated by `mix lumina.test_catalog`"
  end

  test "groups by milestone and sorts by id within a milestone" do
    catalog = Catalog.render([@valid, @invalid, @earlier])

    assert catalog =~ "3 fixtures: 2 valid, 1 invalid."

    headings = Regex.scan(~r/^##+ .*$/m, catalog) |> List.flatten()

    assert headings == [
             "## M0",
             "### `m0-minimal-valid`: Minimal",
             "## M4",
             "### `m4-ca-expired`: Expired CA certificate",
             "### `m4-chain-ok`: Valid chain"
           ]
  end

  test "an entry shows the rationale, expected outcome, RFC links and files" do
    catalog = Catalog.render([@invalid])

    assert catalog =~
             "Catches validators that skip notAfter on CA certificates.\n\n- **Expected:**"

    assert catalog =~
             "- **Expected:** invalid. A validator must reject:\n  - `ta/ca1.cer`: notAfter is in the past\n"

    assert catalog =~
             "[6487 §4.6.2](../rfc/rfc6487.txt) ([html](https://www.rfc-editor.org/rfc/rfc6487.html#section-4.6.2))"

    # Appendices only link to the local copy.
    assert catalog =~ "[5280 §A.1](../rfc/rfc5280.txt)\n"

    assert catalog =~
             "[descriptor](../../test/fixtures/barry/m4-ca-expired/case.repo) · " <>
               "[metadata](../../test/fixtures/barry/m4-ca-expired/case.exs) · " <>
               "[rsync tree](../../test/fixtures/barry/m4-ca-expired/rsync)"
  end

  test "a valid fixture says so" do
    assert Catalog.render([@valid]) =~ "- **Expected:** valid\n"
  end

  test "links are relative to where the catalog is written" do
    catalog = Catalog.render([@valid], "CATALOG.md")
    assert catalog =~ "[6487 §4](doc/rfc/rfc6487.txt)"
    assert catalog =~ "(test/fixtures/barry/m4-chain-ok/case.repo)"
  end

  test "rendering is deterministic regardless of input order" do
    assert Catalog.render([@valid, @invalid, @earlier]) ==
             Catalog.render([@earlier, @invalid, @valid])
  end
end
